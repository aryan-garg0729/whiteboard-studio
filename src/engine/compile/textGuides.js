for (const ch of 'kvx') LOWER[ch] = UPPER[ch.toUpperCase()];
for (const ch of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') if (!LOWER[ch.toLowerCase()]) LOWER[ch.toLowerCase()] = UPPER[ch];

/** Returns normalized guide strokes for a printable ASCII glyph, or null. */
export function guideForCharacter(ch) {
  if (ch === ' ') return [];
  return LOWER[ch] || UPPER[ch] || DIGITS[ch] || PUNCT[ch] || null;
}
